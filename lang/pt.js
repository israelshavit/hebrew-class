// How the texts above name the teacher: "o professor", as the teacher asked.
// For a teacher who'd be "a professora", write "professora", "a professora",
// "sua professora", "da professora"; for either, "professor(a)", "o(a)
// professor(a)", "seu(sua) professor(a)", "do(a) professor(a)".
(function (text) {
  var TEACHER = {
    "professor": "professor",
    "o professor": "o professor",
    "seu professor": "seu professor",
    "do professor": "do professor"
  };
  Object.keys(text).forEach(function (key) {
    text[key] = text[key].replace(/\[([^\]]+)\]/g, function (whole, words) {
      var value = TEACHER[words.charAt(0).toLowerCase() + words.slice(1)];
      if (!value) return whole;
      return words.charAt(0) !== words.charAt(0).toLowerCase() ? value.charAt(0).toUpperCase() + value.slice(1) : value;
    });
  });
})(window.HebrewClass.text.pt);
